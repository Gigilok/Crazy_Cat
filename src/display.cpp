bool displayInit() {
    Wire.begin(OLED_SDA, OLED_SCK);
    Wire.setClock(400000);
    Wire.setTimeout(500);

    if (!display.begin(SSD1306_SWITCHCAPVCC, OLED_ADDRESS)) {
        return false;
    }
    display.clearDisplay();
    display.setTextSize(1);
    display.setTextColor(SSD1306_WHITE);
    display.display();

    // Configura pino ADC da bateria (se habilitado)
#if BATTERY_PIN != 255
    analogReadResolution(12);          // 12 bits (0-4095)
    analogSetAttenuation(ADC_11db);    // ate 3.3V full range
    pinMode(BATTERY_PIN, INPUT);
#endif

    return true;
}

void setBrightness(uint8_t brightness) {
    display.ssd1306_command(SSD1306_SETCONTRAST);
    display.ssd1306_command(brightness);
}

void clearDisplay() { display.clearDisplay(); }
void updateDisplay() { display.display(); }

void drawText(int x, int y, const char* text, uint8_t size) {
    display.setTextSize(size);
    display.setCursor(x, y);
    display.print(text);
}

void drawCenteredText(int y, const char* text, uint8_t size) {
    display.setTextSize(size);
    int16_t x1, y1;
    uint16_t w, h;
    display.getTextBounds(text, 0, 0, &x1, &y1, &w, &h);
    display.setCursor((SCREEN_WIDTH - w) / 2, y);
    display.print(text);
}

